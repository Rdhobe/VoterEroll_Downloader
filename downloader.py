# ── Rate limiter for captcha/API requests ────────────────────────────────

class RateLimiter:
    """
    Token-bucket style rate limiter with global 429 backoff.

    Ensures minimum interval between requests and pauses ALL tasks
    when a 429 is detected anywhere.
    Uses threading.Lock (not asyncio.Lock) to avoid event-loop binding issues.
    """

    def __init__(self, min_interval: float = 0.6):
        self._min_interval = min_interval
        self._lock = threading.Lock()
        self._last_request = 0.0
        self._backoff_until = 0.0

    async def acquire(self):
        """Wait until it's safe to make a request."""
        while True:
            with self._lock:
                now = time.monotonic()

                # Respect global backoff (from 429 responses)
                if now < self._backoff_until:
                    wait = self._backoff_until - now
                    # Release lock, sleep, then retry
                else:
                    elapsed = now - self._last_request
                    if elapsed < self._min_interval:
                        wait = self._min_interval - elapsed
                        # Release lock, sleep, then retry
                    else:
                        # Got our slot — claim it and return
                        self._last_request = time.monotonic()
                        return

            # Sleep outside the lock so we don't block the event loop
            log.debug("Rate limiter: waiting %.2fs", wait)
            await asyncio.sleep(wait)

    def trigger_backoff(self, seconds: float):
        """Signal all tasks to pause for *seconds* (e.g. after a 429)."""
        target = time.monotonic() + seconds
        self._backoff_until = max(self._backoff_until, target)
        log.info("Global backoff triggered: %.0fs pause", seconds)



# ── Strategy 0: Direct PDF download (pre-generated, no captcha) ────────

async def _try_direct_pdf_download(
    session: aiohttp.ClientSession,
    year: int,
    state_cd: str,
    roll_type_ref_id: str,
    pdf_gen_type: str,
    revision_no: int,
    ac_no: int,
    part_no: int,
    lang_cd: str,
    output_path: Path,
) -> bool:
    """
    Try to download a single pre-generated PDF directly from voters.eci.gov.in.

    URL pattern: https://voters.eci.gov.in/eroll/{year}/{state_lower}/{roll_slug}/{ac_no}/{filename}.pdf
    No captcha or authentication needed.
    These are the actual 2026 revision PDFs (pre-generated by ECI).

    Returns True if download succeeded.
    """
    filename = build_filename(
        year=year,
        pdf_gen_type=pdf_gen_type,
        state_cd=state_cd,
        ac_no=ac_no,
        roll_type_ref_id=roll_type_ref_id,
        revision_no=revision_no,
        lang_cd=lang_cd,
        part_no=part_no,
    )
    roll_slug = roll_type_ref_id.lower()
    state_lower = state_cd.lower()

    url = f"{EROLL_DIRECT_URL}/{year}/{state_lower}/{roll_slug}/{ac_no}/{filename}"

    download_headers = {
        "User-Agent": HEADERS["User-Agent"],
        "Referer": HEADERS["Referer"],
        "Accept": "*/*",
    }

    log.debug("Strategy 0: trying direct PDF: %s", url)

    try:
        async with session.get(
            url,
            headers=download_headers,
            timeout=aiohttp.ClientTimeout(total=120),
            allow_redirects=True,
        ) as resp:
            if resp.status == 200:
                ct = resp.headers.get("Content-Type", "")
                if "pdf" in ct.lower():
                    pdf_data = await resp.read()
                    if validate_pdf(pdf_data):
                        output_path.parent.mkdir(parents=True, exist_ok=True)
                        with open(output_path, "wb") as f:
                            f.write(pdf_data)
                        log.info(
                            "Direct PDF OK: AC %s part %s lang=%s (%d bytes, pre-generated 2026)",
                            ac_no, part_no, lang_cd, len(pdf_data),
                        )
                        return True
                    log.debug("Direct PDF invalid (not %sPDF) AC %s part %s", "%", ac_no, part_no)
                else:
                    log.debug("Direct PDF wrong content-type '%s' AC %s part %s", ct, ac_no, part_no)
            else:
                log.debug("Direct PDF HTTP %s for AC %s part %s lang=%s",
                          resp.status, ac_no, part_no, lang_cd)
    except (aiohttp.ClientError, asyncio.TimeoutError) as exc:
        log.debug("Direct PDF error AC %s part %s: %s", ac_no, part_no, exc)

    return False


# ── Strategy 1: Direct ZIP download (whole AC, no captcha) ─────────────

def _parse_part_number(filename: str) -> int | None:
    """Extract part number from a PDF filename found inside a ZIP."""
    patterns = [
        r'-(\d+)-WI\.pdf$',
        r'[Pp]art[_\-]?(\d+)',
        r'_(\d+)\.pdf$',
        r'-(\d+)\.pdf$',
    ]
    for pat in patterns:
        m = re.search(pat, filename, re.IGNORECASE)
        if m:
            return int(m.group(1))
    return None


def _extract_zip_pdfs(
    zip_data: bytes,
    ac_dir: Path,
    ac_no: int,
    pending_parts: set[int],
    roll: dict,
    cfg: dict,
    lang_cd: str | None = None,
) -> set[int]:
    """Extract PDFs from ZIP data, rename to canonical filenames, return extracted part numbers."""
    effective_lang = lang_cd or cfg["lang"]
    ac_dir.mkdir(parents=True, exist_ok=True)
    extracted = set()

    try:
        with zipfile.ZipFile(io.BytesIO(zip_data)) as zf:
            for name in zf.namelist():
                if not name.lower().endswith('.pdf'):
                    continue

                pdf_data = zf.read(name)
                if not validate_pdf(pdf_data):
                    continue

                part_no = _parse_part_number(name)
                if part_no is not None and part_no in pending_parts:
                    filename = build_filename(
                        year=cfg["year"],
                        pdf_gen_type=roll.get("pdfGenType", "EROLLGEN"),
                        state_cd=cfg["state"],
                        ac_no=ac_no,
                        roll_type_ref_id=roll.get("rollTypeRefId", ""),
                        revision_no=roll.get("revisionNo", 1),
                        lang_cd=effective_lang,
                        part_no=part_no,
                    )
                    with open(ac_dir / filename, "wb") as f:
                        f.write(pdf_data)
                    extracted.add(part_no)
                elif part_no is None:
                    with open(ac_dir / Path(name).name, "wb") as f:
                        f.write(pdf_data)
                    log.debug("Saved ZIP entry %s (could not parse part number)", name)
    except (zipfile.BadZipFile, OSError) as exc:
        log.warning("Failed to extract ZIP for AC %s: %s", ac_no, exc)

    return extracted


async def _try_zip_download(
    session: aiohttp.ClientSession,
    year: int,
    state_cd: str,
    roll_type_ref_id: str,
    ac_no: int,
    ac_dir: Path,
    pending_parts: set[int],
    roll: dict,
    cfg: dict,
    lang_cd: str | None = None,
) -> set[int]:
    """
    Try to download all parts for an AC as a ZIP from the direct URL.
    Returns set of successfully extracted part numbers.
    """
    roll_slug = roll_type_ref_id.lower()
    state_lower = state_cd.lower()

    urls = [
        f"{EROLL_DIRECT_URL}/{year}/{state_lower}/{roll_slug}/{ac_no}-eroll.zip",
    ]
    if '-' in roll_slug:
        second = roll_slug.split('-', 1)[1]
        urls.append(f"{EROLL_DIRECT_URL}/{year}/{state_lower}/{second}/{ac_no}-eroll.zip")
    roll_type_lower = roll.get("rollType", "").lower()
    if roll_type_lower and f"sir-{roll_type_lower}" != roll_slug:
        urls.append(f"{EROLL_DIRECT_URL}/{year}/{state_lower}/sir-{roll_type_lower}/{ac_no}-eroll.zip")
        urls.append(f"{EROLL_DIRECT_URL}/{year}/{state_lower}/{roll_type_lower}/{ac_no}-eroll.zip")

    seen = set()
    unique_urls = []
    for u in urls:
        if u not in seen:
            seen.add(u)
            unique_urls.append(u)

    download_headers = {
        "User-Agent": HEADERS["User-Agent"],
        "Referer": HEADERS["Referer"],
        "Accept": "*/*",
    }

    for url in unique_urls:
        try:
            log.info("Trying ZIP download: %s", url)
            async with session.get(
                url,
                headers=download_headers,
                timeout=aiohttp.ClientTimeout(total=180),
                allow_redirects=True,
            ) as resp:
                if resp.status == 200:
                    data = await resp.read()
                    if len(data) > 500 and not data[:5] == b"<html" and not data[:5] == b"<!DOC":
                        extracted = _extract_zip_pdfs(
                            data, ac_dir, ac_no, pending_parts, roll, cfg,
                            lang_cd=lang_cd,
                        )
                        if extracted:
                            log.info(
                                "ZIP download OK for AC %s -- %d parts extracted from %s",
                                ac_no, len(extracted), url,
                            )
                            return extracted
                        log.debug("ZIP downloaded but no matching PDFs found")
                    else:
                        log.debug("ZIP URL returned HTML (SPA fallback): %s", url)
                else:
                    log.debug("ZIP URL returned %s: %s", resp.status, url)
        except (aiohttp.ClientError, asyncio.TimeoutError) as exc:
            log.debug("ZIP download error for %s: %s", url, exc)

    return set()


async def _probe_ac_parts(
    session: aiohttp.ClientSession,
    year: int,
    state_cd: str,
    roll_type_ref_id: str,
    pdf_gen_type: str,
    revision_no: int,
    ac_no: int,
    lang_cd: str,
    max_parts: int = 500,
    concurrency: int = 20,
) -> list[int]:
    """
    Probe the CDN to discover which part numbers exist for an AC.

    Used as fallback when the ECI parts-list API (get-publish-part-list) is blocked.
    Tries lightweight GET requests (first 8 bytes only) to the pre-generated
    PDF URLs concurrently. HEAD is NOT usable here — the ECI CDN answers HEAD
    with 406 and only serves GET (200 + application/pdf for existing parts).
    Stops probing once MAX_CONSECUTIVE_MISSES consecutive parts return non-200.

    Returns a sorted list of discovered part numbers.
    """
    MAX_CONSECUTIVE_MISSES = 5  # Stop after this many consecutive 404s
    roll_slug = roll_type_ref_id.lower()
    state_lower = state_cd.lower()

    from utils import build_filename as _build_filename

    download_headers = {
        "User-Agent": HEADERS["User-Agent"],
        "Referer": HEADERS["Referer"],
        "Accept": "*/*",
    }

    found: list[int] = []
    sem = asyncio.Semaphore(concurrency)

    # Phase 1: probe parts 1..max_parts, stopping early on consecutive misses
    # We batch in chunks to keep memory usage low
    consecutive_misses = 0
    part_no = 1

    log.info(
        "Probing CDN parts for AC %s (lang=%s, slug=%s) — up to %d parts",
        ac_no, lang_cd, roll_slug, max_parts,
    )

    while part_no <= max_parts:
        # Build a batch of up to `concurrency` parts
        batch_end = min(part_no + concurrency - 1, max_parts)
        batch = list(range(part_no, batch_end + 1))

        async def _check(p: int) -> tuple[int, bool]:
            from utils import build_filename as _bf
            filename = _bf(
                year=year,
                pdf_gen_type=pdf_gen_type,
                state_cd=state_cd,
                ac_no=ac_no,
                roll_type_ref_id=roll_type_ref_id,
                revision_no=revision_no,
                lang_cd=lang_cd,
                part_no=p,
            )
            url = f"{EROLL_DIRECT_URL}/{year}/{state_lower}/{roll_slug}/{ac_no}/{filename}"
            async with sem:
                try:
                    # GET (not HEAD): the CDN returns 406 for HEAD requests.
                    # Read only the first bytes, then close — enough to check
                    # status + %PDF magic without downloading the whole file.
                    async with session.get(
                        url,
                        headers=download_headers,
                        timeout=aiohttp.ClientTimeout(total=15),
                        allow_redirects=True,
                    ) as resp:
                        if resp.status != 200:
                            return p, False
                        first = await resp.content.read(8)
                        return p, first[:5] == b"%PDF-"
                except Exception:
                    return p, False

        results = await asyncio.gather(*[_check(p) for p in batch])
        batch_found = sorted(p for p, ok in results if ok)
        found.extend(batch_found)

        # Count trailing misses (from end of batch)
        for p in range(batch_end, part_no - 1, -1):
            hit = any(rp == p and ok for rp, ok in results)
            if hit:
                break
            consecutive_misses += 1
        else:
            consecutive_misses += len(batch)

        # Reset miss counter if we found something in this batch
        if batch_found:
            consecutive_misses = 0

        if consecutive_misses >= MAX_CONSECUTIVE_MISSES:
            log.info(
                "AC %s: probe stopping after %d consecutive misses at part %d (found %d parts)",
                ac_no, consecutive_misses, batch_end, len(found),
            )
            break

        part_no = batch_end + 1

    log.info("AC %s: CDN probe found %d parts: %s", ac_no, len(found),
             found[:10] if len(found) > 10 else found)
    return sorted(found)


# ── Strategy 2: API-based download ────────────────────────────────────

async def _download_from_ext_api(
    session: aiohttp.ClientSession, file_id: str
) -> bytes | None:
    """
    Download a PDF from the external API (returns base64-encoded content).

    GET https://gateway-vpd.eci.gov.in/api/v1/ext-printing-publish/get-published-file?fileId={uuid}
    Response: { "payload": "<base64-PDF>", "refId": "filename.pdf" }
    """
    url = f"{GATEWAY_EXT_API}/ext-printing-publish/get-published-file"
    try:
        async with session.get(
            url, headers=EXT_HEADERS, params={"fileId": file_id},
            timeout=aiohttp.ClientTimeout(total=120),
        ) as resp:
            if resp.status == 200:
                data = await resp.json()
                b64_payload = data.get("payload")
                if b64_payload:
                    pdf_data = base64.b64decode(b64_payload)
                    if validate_pdf(pdf_data):
                        log.debug("Ext API OK for fileId %s (%d bytes)", file_id[:12], len(pdf_data))
                        return pdf_data
                    log.debug("Ext API returned invalid PDF for fileId %s", file_id[:12])
                else:
                    log.debug("Ext API no payload for fileId %s: %s",
                              file_id[:12], data.get("message", "")[:100])
            else:
                log.debug("Ext API returned %s for fileId %s", resp.status, file_id[:12])
    except (aiohttp.ClientError, asyncio.TimeoutError) as exc:
        log.debug("Ext API error for fileId %s: %s", file_id[:12], exc)
    return None


async def download_part(
    session: aiohttp.ClientSession,
    ac_no: int,
    part_no: int,
    district_cd: str,
    published_roll_id: str,
    lang_cd: str,
    state_cd: str,
    output_path: Path,
    rate_limiter: RateLimiter,
    roll_info: dict | None = None,
    cfg: dict | None = None,
    max_attempts: int = MAX_CAPTCHA_ATTEMPTS,
) -> bool:
    """
    Download one PDF part via captcha-based API (generate-published-eroll).

    WARNING: This endpoint generates PDFs on-the-fly with STALE 2025 data.
    It is NOT called from the main download flow. Kept for potential future use
    or debugging. Prefer Strategy 0 (direct PDF) or Strategy 1 (ZIP).

    Returns True on success (file saved), False otherwise.
    """
    url_eroll = f"{GATEWAY_API}/printing-publish/generate-published-eroll"
    solve_attempts = 0
    # Captcha fetch failures previously looped FOREVER (no counter increment),
    # hanging the whole AC when the captcha endpoint is down (e.g. persistent
    # 404). Bound them so the part fails fast and the run moves on.
    MAX_FETCH_FAILURES = 5
    fetch_fails = 0

    while solve_attempts < max_attempts:
        await rate_limiter.acquire()

        try:
            captcha_text, captcha_id = await solver.fetch_and_solve(session)
            fetch_fails = 0
        except aiohttp.ClientResponseError as exc:
            fetch_fails += 1
            if fetch_fails >= MAX_FETCH_FAILURES:
                log.warning(
                    "Captcha fetch failed %d times for AC %s part %s (%s) -- giving up on part",
                    fetch_fails, ac_no, part_no, exc,
                )
                return False
            if exc.status == 429:
                backoff = random.uniform(5, 15)
                rate_limiter.trigger_backoff(backoff)
                continue
            log.debug("Captcha error AC %s part %s: %s", ac_no, part_no, exc)
            await asyncio.sleep(2)
            continue
        except Exception as exc:
            fetch_fails += 1
            if fetch_fails >= MAX_FETCH_FAILURES:
                log.warning(
                    "Captcha fetch failed %d times for AC %s part %s (%s) -- giving up on part",
                    fetch_fails, ac_no, part_no, exc,
                )
                return False
            log.debug("Captcha error AC %s part %s: %s", ac_no, part_no, exc)
            await asyncio.sleep(2)
            continue

        body = {
            "stateCd": state_cd,
            "acNumber": ac_no,
            "partNumberList": [part_no],
            "districtCd": district_cd,
            "langCd": lang_cd,
            "publishedRollId": published_roll_id,
            "captcha": captcha_text,
            "captchaId": captcha_id,
        }

        try:
            async with session.post(
                url_eroll, headers=HEADERS, json=body,
                timeout=aiohttp.ClientTimeout(total=REQUEST_TIMEOUT),
            ) as resp:
                if resp.status == 429:
                    backoff = random.uniform(8, 20)
                    rate_limiter.trigger_backoff(backoff)
                    log.warning("429 on generate AC %s part %s -- backoff %.0fs",
                                ac_no, part_no, backoff)
                    continue

                if resp.status == 400:
                    solve_attempts += 1
                    try:
                        err_body = await resp.json()
                        log.debug("Wrong captcha AC %s part %s solve %s/%s: %s",
                                  ac_no, part_no, solve_attempts, max_attempts,
                                  err_body.get("message", ""))
                    except Exception:
                        pass
                    continue

                if resp.status >= 400:
                    log.debug("HTTP %s AC %s part %s", resp.status, ac_no, part_no)
                    solve_attempts += 1
                    continue

                data = await resp.json()
                if data.get("status") != "Success":
                    solve_attempts += 1
                    log.debug("Error AC %s part %s: %s",
                              ac_no, part_no, data.get("message", ""))
                    continue

                payload = data.get("payload", [])
                if not payload:
                    solve_attempts += 1
                    continue

                for ref_id in payload:
                    if not isinstance(ref_id, str):
                        continue
                    pdf_data = await _download_from_ext_api(session, ref_id)
                    if pdf_data:
                        output_path.parent.mkdir(parents=True, exist_ok=True)
                        with open(output_path, "wb") as f:
                            f.write(pdf_data)
                        log.warning(
                            "Downloaded via generate-published-eroll (may contain stale 2025 data): "
                            "AC %s part %s", ac_no, part_no,
                        )
                        return True

                solve_attempts += 1

        except (aiohttp.ClientError, asyncio.TimeoutError) as exc:
            log.debug("Network error AC %s part %s: %s", ac_no, part_no, exc)
            await asyncio.sleep(2)
            solve_attempts += 1

    return False


# ── Orchestrator ─────────────────────────────────────────────────────────

class DownloadStats:
    """Mutable counters shared across tasks, with optional progress callback."""

    def __init__(self, progress_callback=None):
        self.downloaded = 0
        self.skipped = 0
        self.failed = 0
        self.total_bytes = 0
        self.acs_done = 0
        self.total_acs = 0
        self.districts_done = 0
        self.total_districts = 0
        self.total_parts = 0
        self.already_done = 0
        self.start_time = time.time()
        self.current_ac = ""
        self.current_district = ""
        self.ac_plan: dict[int, dict] = {}
        self._progress_callback = progress_callback
        self.lock = threading.Lock()

    def _notify(self):
        """Push a progress snapshot to the callback (if set)."""
        if not self._progress_callback:
            return
        elapsed = max(time.time() - self.start_time, 0.1)
        processed = self.downloaded + self.failed
        speed = self.downloaded / elapsed * 60  # parts per minute
        pending = max(0, self.total_parts - self.already_done - processed)
        eta = (pending / speed * 60) if speed > 0 else 0
        accuracy = (self.downloaded / processed * 100) if processed > 0 else 100.0

        self._progress_callback({
            "total_parts": self.total_parts,
            "already_done": self.already_done,
            "downloaded": self.downloaded,
            "failed": self.failed,
            "pending": pending,
            "total_bytes": self.total_bytes,
            "elapsed_sec": int(elapsed),
            "speed_ppm": round(speed, 1),
            "eta_sec": int(eta),
            "accuracy_pct": round(accuracy, 1),
            "current_district": self.current_district,
            "current_ac": self.current_ac,
            "districts_done": self.districts_done,
            "total_districts": self.total_districts,
            "acs_done": self.acs_done,
            "total_acs": self.total_acs,
            "ac_stats": [v for v in self.ac_plan.values()],
        })

    async def inc_downloaded(self, size: int = 0, ac_no: int = 0):
        with self.lock:
            self.downloaded += 1
            self.total_bytes += size
            if ac_no and ac_no in self.ac_plan:
                self.ac_plan[ac_no]["done"] += 1
        self._notify()

    async def inc_skipped(self):
        with self.lock:
            self.skipped += 1

    async def inc_failed(self, ac_no: int = 0, part_no: int = 0):
        with self.lock:
            self.failed += 1
            if ac_no and ac_no in self.ac_plan:
                self.ac_plan[ac_no]["failed"] += 1
                if part_no:
                    self.ac_plan[ac_no].setdefault("failed_parts", []).append(part_no)
        self._notify()

    async def inc_acs_done(self, ac_no: int = 0):
        with self.lock:
            self.acs_done += 1
            if ac_no and ac_no in self.ac_plan:
                self.ac_plan[ac_no]["status"] = "completed"
        self._notify()

    async def inc_districts_done(self):
        with self.lock:
            self.districts_done += 1
        self._notify()


async def _process_part(
    sem: asyncio.Semaphore,
    session: aiohttp.ClientSession,
    ac: dict,
    part_no: int,
    roll_info: dict,
    cfg: dict,
    ac_dir: Path,
    completed: set[int],
    stats: DownloadStats,
    pbar: tqdm,
    rate_limiter: RateLimiter,
    lang_cd: str | None = None,
):
    """Download a single part under the semaphore.

    Strategy 0 (direct PDF from voters.eci.gov.in) is tried first — guaranteed
    correct 2026 data for states that have CDN-hosted pre-generated PDFs.

    If Strategy 0 fails (404), falls back to the captcha-based API
    (generate-published-eroll). This is needed for states using BY-EROLLGEN
    (Karnataka, Maharashtra) which don't have CDN files. Note: the captcha API
    may return stale 2025 data for some states.
    """
    effective_lang = lang_cd or cfg["lang"]
    async with sem:
        filename = build_filename(
            year=cfg["year"],
            pdf_gen_type=roll_info["pdfGenType"],
            state_cd=cfg["state"],
            ac_no=ac["asmblyNo"],
            roll_type_ref_id=roll_info["rollTypeRefId"],
            revision_no=roll_info["revisionNo"],
            lang_cd=effective_lang,
            part_no=part_no,
        )
        output_path = ac_dir / filename

        # Strategy 0: Direct PDF download (pre-generated 2026 data, no captcha)
        ok = await _try_direct_pdf_download(
            session=session,
            year=cfg["year"],
            state_cd=cfg["state"],
            roll_type_ref_id=roll_info["rollTypeRefId"],
            pdf_gen_type=roll_info["pdfGenType"],
            revision_no=roll_info["revisionNo"],
            ac_no=ac["asmblyNo"],
            part_no=part_no,
            lang_cd=effective_lang,
            output_path=output_path,
        )

        # Strategy 2 fallback: Captcha-based API (if direct URL failed)
        if not ok:
            log.info(
                "Direct PDF not available for AC %s part %s (lang=%s), "
                "trying captcha API fallback...",
                ac["asmblyNo"], part_no, effective_lang,
            )
            published_roll_id = roll_info.get("id") or \
                f"{cfg['state']}-{cfg['year']}-{roll_info['rollType']}"
            ok = await download_part(
                session=session,
                ac_no=ac["asmblyNo"],
                part_no=part_no,
                district_cd=ac["districtCd"],
                published_roll_id=published_roll_id,
                lang_cd=effective_lang,
                state_cd=cfg["state"],
                output_path=output_path,
                rate_limiter=rate_limiter,
                roll_info=roll_info,
                cfg=cfg,
            )

        if ok:
            size = output_path.stat().st_size if output_path.exists() else 0
            await stats.inc_downloaded(size, ac["asmblyNo"])
            completed.add(part_no)
            await save_ac_progress(ac_dir, completed)
            await clear_failed_part(ac_dir, part_no)
            log.debug("OK  AC %s part %s", ac["asmblyNo"], part_no)
        else:
            await stats.inc_failed(ac["asmblyNo"], part_no)
            await record_failed_part(
                ac_dir, ac["asmblyNo"], part_no,
                "Download failed: direct URL 404 and captcha API failed",
            )
            log.warning("FAIL AC %s part %s -- all download strategies failed",
                        ac["asmblyNo"], part_no)

        pbar.update(1)
        pbar.set_postfix_str(
            f"OK {stats.downloaded}  X {stats.failed}  "
            f"AC {stats.acs_done}/{stats.total_acs}  "
            f"Dist {stats.districts_done}/{stats.total_districts}"
        )


async def run(cfg: dict) -> dict:
    """
    Main entry point for the download engine.

    *cfg* keys: state, lang, year, output, concurrency, resume,
                dry_run, ac_filter, district_filters, start_part, end_part

    Flow: State -> Roll Type -> Districts -> ACs per district -> Parts
    Downloads district-by-district, AC-by-AC within each district.

    Returns a summary dict.
    """
    # Create a per-call rate limiter (each download thread gets its own,
    # so concurrent downloads from multiple tabs are safe)
    rate_limiter = RateLimiter(min_interval=0.6)

    state_cd = cfg["state"]
    state_name = STATE_NAMES.get(state_cd, state_cd)
    lang_name = LANG_MAP.get(cfg["lang"], cfg["lang"])
    t0 = time.time()

    connector = aiohttp.TCPConnector(limit=cfg["concurrency"] + 10, ssl=False)
    async with aiohttp.ClientSession(connector=connector) as session:

        # 1. Roll type
        # If a roll type was pre-resolved by the web UI (browse.py), use it directly
        # to avoid hitting the live ECI API (which often returns 400 when blocked).
        _preresolved_roll = cfg.get("roll_type_info")
        if _preresolved_roll:
            roll = _preresolved_roll
            log.info(
                "Roll type (pre-resolved from UI): %s | revision %s",
                roll.get("displayName", roll.get("rollTypeRefId", "?")), roll.get("revisionNo", 1),
            )
        else:
            try:
                roll_types = await get_roll_types(session, state_cd, cfg["year"])
            except Exception as exc:
                log.warning(
                    "ECI roll-types API failed (%s) — using CDN slug fallback for %s/%s",
                    exc, state_cd, cfg["year"],
                )
                roll_types = []

            if not roll_types:
                # Fallback: construct a known CDN slug (same logic as browse.py)
                import re as _re
                _SLUG = "sir-finalroll-2026"
                slug = _re.sub(r'\d{4}', str(cfg["year"]), _SLUG)
                roll = {
                    "rollType": "FINALROLL",
                    "rollTypeRefId": slug,
                    "pdfGenType": "PART",
                    "revisionNo": 1,
                    "displayName": f"Final Electoral Roll {cfg['year']} (fallback)",
                    "publish": "Y",
                    "_fallback": True,
                }
                log.warning(
                    "Using CDN slug fallback roll type '%s' for %s/%s — "
                    "ECI gateway API blocked or returned no data",
                    slug, state_cd, cfg["year"],
                )
            else:
                # Prefer SIR FinalRoll (EROLLGEN) over blindly taking the
                # first published roll. roll_types[0] is currently
                # Supplement-2 (rollType=None, SUPPLEMENTGEN), whose
                # get-publish-part-list rejects with 400 and whose
                # CDN slug (all_together) has no pre-generated PDFs.
                roll = next(
                    (
                        r for r in roll_types
                        if r.get("rollTypeRefId") == "SIR-FinalRoll"
                        and r.get("pdfGenType") == "EROLLGEN"
                    ),
                    None,
                )
                if roll is None:
                    roll = roll_types[0]
                    log.warning(
                        "SIR FinalRoll not found; using first published roll: %s",
                        roll.get("displayName", "unknown"),
                    )
                log.info(
                    "Roll type: %s | rollTypeRefId %s | pdfGenType %s | "
                    "published %s | revision %s",
                    roll["displayName"],
                    roll.get("rollTypeRefId", "?"),
                    roll.get("pdfGenType", "?"),
                    roll.get("publishDate", "?"),
                    roll["revisionNo"],
                )

        # 2. AC list
        try:
            all_acs = await get_constituencies(session, state_cd)
        except Exception as exc:
            log.error("Failed to fetch constituencies for %s: %s", state_cd, exc)
            return {"error": f"Could not fetch constituency list: {exc}"}
        if not all_acs:
            log.error("No constituencies returned for %s", state_cd)
            return {"error": "No constituencies"}
        log.info("Total ACs for %s: %d", state_name, len(all_acs))

        # 3. Build district -> ACs mapping
        districts = get_districts_from_ac_list(all_acs, state_cd=state_cd)
        district_acs: dict[str, list[dict]] = defaultdict(list)
        for ac in all_acs:
            district_acs[ac["districtCd"]].append(ac)

        # Apply district filter (matches against name OR code)
        district_filters = cfg.get("district_filters", [])
        if district_filters:
            filtered_districts = {}
            for dcd, dname in districts.items():
                for df in district_filters:
                    df_lower = df.lower()
                    if df_lower in dname.lower() or df_lower in dcd.lower():
                        filtered_districts[dcd] = dname
                        break
            districts = filtered_districts

        if not districts:
            log.error("No districts match the given filters")
            return {"error": "No districts after filter"}

        # Apply AC filter
        ac_filter = cfg.get("ac_filter")

        log.info("Districts to process: %d", len(districts))
        for dcd, dname in districts.items():
            acs_in_dist = district_acs.get(dcd, [])
            if ac_filter:
                acs_in_dist = [a for a in acs_in_dist if a["asmblyNo"] == ac_filter]
            log.info("  %s: %d ACs", dname, len(acs_in_dist))

        # 4. Gather parts for all ACs across all districts
        # Structure: district_cd -> [(ac, part_no, ac_dir, completed_set, lang_cd), ...]
        district_tasks: dict[str, list[tuple]] = defaultdict(list)
        # ACs where no part list could be determined (try ZIP then captcha on download)
        discovery_acs: dict[str, list[tuple]] = defaultdict(list)
        total_parts = 0
        total_already = 0
        total_acs_count = 0
        ac_plan_data: dict[int, dict] = {}  # per-AC progress plan

        # Cache resolved language per AC to avoid duplicate API calls
        ac_lang_cache: dict[int, str] = {}

        log.info("Fetching part lists and languages ...")
        for dcd, dname in districts.items():
            acs_in_dist = sorted(district_acs.get(dcd, []), key=lambda a: a["asmblyNo"])
            if ac_filter:
                acs_in_dist = [a for a in acs_in_dist if a["asmblyNo"] == ac_filter]

            for ac in acs_in_dist:
                # Resolve language for this AC
                ac_no = ac["asmblyNo"]
                if ac_no not in ac_lang_cache:
                    try:
                        ac_langs = await get_ac_languages(
                            session, state_cd, ac_no,
                            roll["rollTypeRefId"], roll["pdfGenType"],
                        )
                    except Exception as exc:
                        log.warning("Failed to fetch languages for AC %s: %s", ac_no, exc)
                        ac_langs = {}

                    requested = cfg["lang"]
                    if ac_langs:
                        if requested in ac_langs:
                            resolved = requested
                        elif "ENG" in ac_langs:
                            # Requested lang not available but English is — use English
                            resolved = "ENG"
                            log.info(
                                "AC %s: '%s' not available, using ENG (ENGLISH). Available: %s",
                                ac_no, requested,
                                ", ".join(f"{k}={v}" for k, v in ac_langs.items()),
                            )
                        elif len(ac_langs) == 1:
                            # Only one language available — use it
                            resolved = next(iter(ac_langs))
                            log.info(
                                "AC %s: '%s' not available, only '%s' (%s) available -- using it",
                                ac_no, requested, resolved, ac_langs[resolved],
                            )
                        else:
                            # Multiple non-English languages — ask user
                            ac_name = ac.get("asmblyName", str(ac_no))
                            print(f"\n  AC {ac_no} ({ac_name}): '{requested}' not available.")
                            print(f"  Available languages:")
                            lang_keys = list(ac_langs.keys())
                            for i, (code, name) in enumerate(ac_langs.items(), 1):
                                print(f"    {i}. {code} ({name})")
                            try:
                                choice = input(f"  Select language [1-{len(lang_keys)}]: ").strip()
                                idx = int(choice) - 1
                                if 0 <= idx < len(lang_keys):
                                    resolved = lang_keys[idx]
                                else:
                                    resolved = lang_keys[0]
                            except (ValueError, EOFError):
                                resolved = lang_keys[0]
                            log.info("AC %s: user selected '%s' (%s)", ac_no, resolved, ac_langs[resolved])
                    else:
                        # API returned empty — try with requested language anyway
                        resolved = requested
                        log.debug("AC %s: language API returned empty, using '%s'", ac_no, requested)

                    ac_lang_cache[ac_no] = resolved

                resolved_lang = ac_lang_cache[ac_no]

                # ── Resolve part list ──────────────────────────────────────
                # Try the live ECI API first; fall back to CDN probe if blocked.
                parts = []
                _use_fallback_roll = roll.get("_fallback") or roll.get("rollTypeRefId", "").startswith("sir-")

                if not _use_fallback_roll:
                    try:
                        parts = await get_part_list(
                            session, state_cd, ac_no, cfg["year"],
                            roll["rollType"], roll["rollTypeRefId"],
                            roll["pdfGenType"], roll["revisionNo"],
                        )
                    except Exception as exc:
                        log.warning(
                            "AC %s: get_part_list API failed (%s) — switching to CDN probe fallback",
                            ac_no, exc,
                        )
                        parts = []

                if not parts:
                    # Fallback: probe CDN to discover parts without the API
                    log.info(
                        "AC %s %s: part list empty or API blocked — probing CDN for parts",
                        ac_no, ac.get("asmblyName", ""),
                    )
                    parts = await _probe_ac_parts(
                        session=session,
                        year=cfg["year"],
                        state_cd=state_cd,
                        roll_type_ref_id=roll.get("rollTypeRefId", ""),
                        pdf_gen_type=roll.get("pdfGenType", "PART"),
                        revision_no=roll.get("revisionNo", 1),
                        ac_no=ac_no,
                        lang_cd=resolved_lang,
                        max_parts=1000,  # UP ACs exceed 500 parts (e.g. AC86 has 520)
                        concurrency=cfg.get("concurrency", 10),
                    )

                if not parts:
                    # Can't determine parts — queue for discovery mode (ZIP → captcha probe)
                    log.warning(
                        "AC %s %s: no parts found via API or CDN probe — queuing for discovery mode",
                        ac_no, ac.get("asmblyName", ""),
                    )
                    ac_dir_disc = build_ac_dir(
                        cfg["output"], state_cd, dname,
                        ac_no, ac.get("asmblyName", str(ac_no)),
                    )
                    completed_disc: set[int] = set()
                    if cfg.get("resume"):
                        completed_disc = load_ac_progress(ac_dir_disc)
                    discovery_acs[dcd].append((ac, ac_dir_disc, completed_disc, resolved_lang))
                    total_acs_count += 1
                    ac_plan_data[ac_no] = {
                        "ac_no": ac_no,
                        "ac_name": ac.get("asmblyName", str(ac_no)),
                        "district": dname,
                        "total": 0,
                        "already_done": len(completed_disc),
                        "pending": 1,
                        "done": 0,
                        "failed": 0,
                        "status": "pending",
                    }
                    continue

                # Part range filter
                if cfg.get("start_part"):
                    parts = [p for p in parts if p >= cfg["start_part"]]
                if cfg.get("end_part"):
                    parts = [p for p in parts if p <= cfg["end_part"]]

                ac_dir = build_ac_dir(
                    cfg["output"], state_cd, dname,
                    ac_no, ac.get("asmblyName", str(ac_no)),
                )

                # Migrate old directory naming: district CODE (S2519) → district NAME (Bankura)
                # If an old-style directory exists but the new one doesn't, rename it
                if dcd != dname:
                    old_ac_dir = build_ac_dir(
                        cfg["output"], state_cd, dcd,
                        ac_no, ac.get("asmblyName", str(ac_no)),
                    )
                    if old_ac_dir.exists() and not ac_dir.exists():
                        ac_dir.parent.mkdir(parents=True, exist_ok=True)
                        try:
                            old_ac_dir.rename(ac_dir)
                            log.info("Migrated AC %s directory: %s -> %s",
                                     ac_no, old_ac_dir.name, ac_dir.parent.name)
                        except OSError as exc:
                            log.warning("Could not migrate AC %s dir: %s", ac_no, exc)

                completed: set[int] = set()
                if cfg.get("force"):
                    # Force re-download: clear progress and delete old PDFs
                    import shutil
                    # Clear both old (code-based) and new (name-based) directories
                    for force_dir in [ac_dir, build_ac_dir(cfg["output"], state_cd, dcd,
                                      ac_no, ac.get("asmblyName", str(ac_no)))]:
                        if force_dir.exists():
                            log.info("Force mode: clearing %s", force_dir)
                            shutil.rmtree(force_dir, ignore_errors=True)
                elif cfg.get("resume"):
                    completed = load_ac_progress(ac_dir)

                pending = get_pending_parts(parts, completed)
                total_parts += len(parts)
                total_already += len(completed)
                total_acs_count += 1

                ac_plan_data[ac_no] = {
                    "ac_no": ac_no,
                    "ac_name": ac.get("asmblyName", str(ac_no)),
                    "district": dname,
                    "total": len(parts),
                    "already_done": len(completed),
                    "pending": len(pending),
                    "done": 0,
                    "failed": 0,
                    "status": "pending" if pending else "completed",
                }

                for p in pending:
                    district_tasks[dcd].append((ac, p, ac_dir, completed, resolved_lang))

        has_discovery = any(discovery_acs.values())
        pending_count = sum(len(tasks) for tasks in district_tasks.values())
        log.info(
            "Parts: %d total, %d already done, %d pending across %d ACs in %d districts",
            total_parts, total_already, pending_count, total_acs_count, len(districts),
        )
        if has_discovery:
            disc_count = sum(len(v) for v in discovery_acs.values())
            log.info("%d ACs queued for discovery mode (ZIP/captcha probe)", disc_count)

        if cfg.get("dry_run"):
            log.info("DRY RUN -- would download %d parts (+%d discovery ACs)",
                     pending_count, sum(len(v) for v in discovery_acs.values()))
            for dcd, dname in districts.items():
                tasks = district_tasks.get(dcd, [])
                ac_set = set(ac["asmblyNo"] for ac, _, _, _, _ in tasks)
                log.info("  %s: %d pending parts across %d ACs", dname, len(tasks), len(ac_set))
            return {"dry_run": True, "pending": pending_count}

        if pending_count == 0 and not has_discovery:
            log.info("Nothing to download -- all parts complete!")
            return {"downloaded": 0, "skipped": total_already, "failed": 0}

        # 5. Download district-by-district, AC-by-AC
        stats = DownloadStats(progress_callback=cfg.get("progress_callback"))
        stats.total_acs = total_acs_count
        stats.total_districts = len(districts)
        stats.total_parts = total_parts
        stats.already_done = total_already
        stats.ac_plan = ac_plan_data
        stats._notify()  # send initial snapshot

        # Concurrency: limit to sensible level since captcha is the bottleneck
        # The rate limiter serializes captcha calls, so concurrency only controls
        # how many tasks are waiting in the pipeline.
        effective_concurrency = min(cfg["concurrency"], 10)
        sem = asyncio.Semaphore(effective_concurrency)
        log.info("Effective concurrency: %d (rate-limited by captcha endpoint)", effective_concurrency)

        pbar = tqdm(
            total=pending_count,
            desc="Downloading",
            unit="part",
            bar_format=(
                "{l_bar}{bar}| {n_fmt}/{total_fmt} parts | "
                "{rate_fmt} | ETA: {remaining} | {postfix}"
            ),
        )
        pbar.set_postfix_str(
            f"OK 0  X 0  AC 0/{stats.total_acs}  Dist 0/{stats.total_districts}"
        )

        for dcd, dname in districts.items():
            tasks_for_district = district_tasks.get(dcd, [])
            if not tasks_for_district:
                await stats.inc_districts_done()
                continue

            stats.current_district = dname
            tqdm.write(f"\n{'='*50}")
            tqdm.write(f"  District: {dname}")
            tqdm.write(f"{'='*50}")

            # Group by AC within this district
            ac_groups: dict[int, list] = defaultdict(list)
            for ac, part_no, ac_dir, completed, lang_cd in tasks_for_district:
                ac_groups[ac["asmblyNo"]].append((ac, part_no, ac_dir, completed, lang_cd))

            for ac_no in sorted(ac_groups.keys()):
                tasks_for_ac = ac_groups[ac_no]
                ac_start = time.time()
                ac_info = tasks_for_ac[0][0]
                ac_dir = tasks_for_ac[0][2]
                completed = tasks_for_ac[0][3]
                ac_lang = tasks_for_ac[0][4]

                ac_name_str = ac_info.get("asmblyName", str(ac_no))
                stats.current_ac = f"{ac_no} - {ac_name_str}"
                if ac_no in stats.ac_plan:
                    stats.ac_plan[ac_no]["status"] = "downloading"
                stats._notify()
                tqdm.write(f"    AC {ac_no} {ac_name_str}: lang={ac_lang}")

                remaining_tasks = list(tasks_for_ac)

                # -- Strategy 1: Try direct ZIP download (no captcha) --
                pending_parts = set(p for _, p, _, _, _ in tasks_for_ac)
                zip_extracted = await _try_zip_download(
                    session, cfg["year"], cfg["state"],
                    roll.get("rollTypeRefId", ""),
                    ac_no, ac_dir, pending_parts, roll, cfg,
                    lang_cd=ac_lang,
                )
                if zip_extracted:
                    for part_no in zip_extracted:
                        completed.add(part_no)
                        size = 0
                        fname = build_filename(
                            year=cfg["year"],
                            pdf_gen_type=roll.get("pdfGenType", "EROLLGEN"),
                            state_cd=cfg["state"],
                            ac_no=ac_no,
                            roll_type_ref_id=roll.get("rollTypeRefId", ""),
                            revision_no=roll.get("revisionNo", 1),
                            lang_cd=ac_lang,
                            part_no=part_no,
                        )
                        fpath = ac_dir / fname
                        if fpath.exists():
                            size = fpath.stat().st_size
                        await stats.inc_downloaded(size, ac_no)
                        pbar.update(1)
                        pbar.set_postfix_str(
                            f"OK {stats.downloaded}  X {stats.failed}  "
                            f"AC {stats.acs_done}/{stats.total_acs}  "
                            f"Dist {stats.districts_done}/{stats.total_districts}"
                        )
                    await save_ac_progress(ac_dir, completed)

                    remaining_tasks = [
                        (ac, p, d, c, l) for ac, p, d, c, l in tasks_for_ac
                        if p not in zip_extracted
                    ]
                    if remaining_tasks:
                        tqdm.write(
                            f"    AC {ac_no}: ZIP got {len(zip_extracted)}/{len(pending_parts)} parts, "
                            f"downloading {len(remaining_tasks)} remaining via API"
                        )
                    else:
                        tqdm.write(
                            f"    AC {ac_no}: ZIP got ALL {len(zip_extracted)} parts!"
                        )

                # -- Per-part direct PDF download (Strategy 0, no captcha) --
                if remaining_tasks:
                    coros = [
                        _process_part(
                            sem, session, ac, part_no, roll, cfg,
                            ac_dir, completed, stats, pbar,
                            rate_limiter=rate_limiter,
                            lang_cd=lang,
                        )
                        for ac, part_no, ac_dir, completed, lang in remaining_tasks
                    ]
                    await asyncio.gather(*coros)

                elapsed = time.time() - ac_start
                ac_name = ac_info.get("asmblyName", str(ac_no))
                n_parts = len(tasks_for_ac)
                await stats.inc_acs_done(ac_no)
                mins, secs = divmod(int(elapsed), 60)
                tqdm.write(
                    f"    AC {ac_no} {ac_name}: "
                    f"{n_parts} parts done ({mins}m {secs:02d}s)"
                )

            await stats.inc_districts_done()
            tqdm.write(f"  District {dname}: DONE")

        # ── Discovery-mode ACs (no part list found) ─────────────────────────
        # Try ZIP for the whole AC, then captcha sequential probe.
        if has_discovery:
            tqdm.write(f"\n{'='*50}")
            tqdm.write("  Discovery Mode: probing ACs with unknown part lists")
            tqdm.write(f"{'='*50}")
            for dcd, dname in districts.items():
                for ac, ac_dir, completed, lang_cd in discovery_acs.get(dcd, []):
                    ac_no = ac["asmblyNo"]
                    ac_name = ac.get("asmblyName", str(ac_no))
                    ac_start = time.time()
                    stats.current_district = dname
                    stats.current_ac = f"{ac_no} - {ac_name}"
                    if ac_no in stats.ac_plan:
                        stats.ac_plan[ac_no]["status"] = "downloading"
                    stats._notify()
                    tqdm.write(f"    [Discovery] AC {ac_no} {ac_name} ({lang_cd})")

                    # Step 1: Try ZIP download for the full AC
                    all_probe_parts = set(range(1, 501))
                    zip_extracted = await _try_zip_download(
                        session, cfg["year"], cfg["state"],
                        roll.get("rollTypeRefId", ""),
                        ac_no, ac_dir, all_probe_parts, roll, cfg,
                        lang_cd=lang_cd,
                    )
                    if zip_extracted:
                        for part_no in zip_extracted:
                            completed.add(part_no)
                            fpath = ac_dir / build_filename(
                                year=cfg["year"],
                                pdf_gen_type=roll.get("pdfGenType", "EROLLGEN"),
                                state_cd=cfg["state"], ac_no=ac_no,
                                roll_type_ref_id=roll.get("rollTypeRefId", ""),
                                revision_no=roll.get("revisionNo", 1),
                                lang_cd=lang_cd, part_no=part_no,
                            )
                            size = fpath.stat().st_size if fpath.exists() else 0
                            # Update total so UI progress bar becomes meaningful
                            stats.total_parts += 1
                            if ac_no in stats.ac_plan:
                                stats.ac_plan[ac_no]["total"] = len(zip_extracted)
                                stats.ac_plan[ac_no]["pending"] = max(0, len(zip_extracted) - len(completed))
                            await stats.inc_downloaded(size, ac_no)
                            pbar.update(1)
                        await save_ac_progress(ac_dir, completed)
                        tqdm.write(f"    [Discovery] AC {ac_no}: ZIP found {len(zip_extracted)} parts")
                        await stats.inc_acs_done(ac_no)
                        continue

                    # Step 2: Sequential captcha probe (parts 1..N)
                    tqdm.write(f"    [Discovery] AC {ac_no}: ZIP failed — trying captcha probe (max 3 min)")
                    MAX_CONSEC = 5   # stop after 5 consecutive failures
                    PROBE_TIMEOUT = 180  # seconds — don't probe forever
                    consec_fail = 0
                    part_no = 1
                    probe_start = time.time()
                    while part_no <= 500 and consec_fail < MAX_CONSEC and (time.time() - probe_start) < PROBE_TIMEOUT:

                        if part_no in completed:
                            part_no += 1
                            consec_fail = 0
                            continue
                        filename = build_filename(
                            year=cfg["year"],
                            pdf_gen_type=roll.get("pdfGenType", "EROLLGEN"),
                            state_cd=cfg["state"], ac_no=ac_no,
                            roll_type_ref_id=roll.get("rollTypeRefId", ""),
                            revision_no=roll.get("revisionNo", 1),
                            lang_cd=lang_cd, part_no=part_no,
                        )
                        output_path = ac_dir / filename
                        # Try direct PDF first
                        ok = await _try_direct_pdf_download(
                            session, cfg["year"], cfg["state"],
                            roll.get("rollTypeRefId", ""), roll.get("pdfGenType", "EROLLGEN"),
                            roll.get("revisionNo", 1), ac_no, part_no, lang_cd, output_path,
                        )
                        if not ok:
                            # Captcha API fallback
                            published_roll_id = roll.get("id") or \
                                f"{cfg['state']}-{cfg['year']}-{roll.get('rollType', 'FINALROLL')}"
                            ok = await download_part(
                                session=session, ac_no=ac_no, part_no=part_no,
                                district_cd=ac["districtCd"],
                                published_roll_id=published_roll_id,
                                lang_cd=lang_cd, state_cd=cfg["state"],
                                output_path=output_path,
                                rate_limiter=rate_limiter, roll_info=roll, cfg=cfg,
                            )
                        if ok:
                            size = output_path.stat().st_size if output_path.exists() else 0
                            # Update total so UI switches to real progress bar
                            stats.total_parts += 1
                            if ac_no in stats.ac_plan:
                                stats.ac_plan[ac_no]["total"] = stats.ac_plan[ac_no].get("total", 0) + 1
                            await stats.inc_downloaded(size, ac_no)
                            completed.add(part_no)
                            await save_ac_progress(ac_dir, completed)
                            consec_fail = 0
                            pbar.update(1)
                        else:
                            consec_fail += 1
                        part_no += 1

                    if stats.ac_plan.get(ac_no, {}).get("done", 0) == 0:
                        tqdm.write(f"    [Discovery] AC {ac_no}: no parts downloaded (state may require special access)")
                    else:
                        elapsed = time.time() - ac_start
                        mins, secs = divmod(int(elapsed), 60)
                        tqdm.write(f"    [Discovery] AC {ac_no}: {stats.ac_plan[ac_no]['done']} parts ({mins}m {secs:02d}s)")
                    await stats.inc_acs_done(ac_no)

        pbar.close()


    elapsed = time.time() - t0
    hours, rem = divmod(int(elapsed), 3600)
    mins, secs = divmod(rem, 60)
    speed = stats.downloaded / (elapsed / 60) if elapsed > 0 else 0
    gb = stats.total_bytes / (1024 ** 3)

    # Count failed from per-AC failed.json files
    state_output_dir = Path(cfg["output"]) / safe_name(state_name)
    failed_total = count_failed_parts_in_dir(state_output_dir)

    summary = {
        "state": f"{state_name} ({state_cd})",
        "language": f"{lang_name} ({cfg['lang']})",
        "total_districts": stats.total_districts,
        "total_acs": stats.total_acs,
        "total_parts": total_parts,
        "downloaded": stats.downloaded,
        "skipped": stats.skipped + total_already,
        "failed": failed_total,
        "time": f"{hours}h {mins:02d}m",
        "speed": f"{speed:.1f} parts/min",
        "data": f"{gb:.1f} GB",
    }

    print()
    print("=" * 48)
    print("  ECI Electoral Roll Download -- Summary")
    print("=" * 48)
    for label, key in [
        ("State", "state"),
        ("Language", "language"),
        ("Districts", "total_districts"),
        ("Total ACs", "total_acs"),
        ("Total Parts", "total_parts"),
        ("Downloaded", "downloaded"),
        ("Already Done", "skipped"),
        ("Failed", "failed"),
        ("Time Taken", "time"),
        ("Avg Speed", "speed"),
        ("Data Saved", "data"),
    ]:
        val = summary[key]
        suffix = ""
        if key == "downloaded":
            suffix = "  [OK]"
        elif key == "failed" and val:
            suffix = "  [FAIL] -> see failed.json in AC folders"
        elif key == "skipped":
            suffix = "  (skipped)"
        print(f"  {label:<16}: {val}{suffix}")
    print("=" * 48)

    return summary
